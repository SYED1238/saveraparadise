-- ------------------------------------------------------------------------------
-- 5. SECURE RIDER PIN VERIFICATION RPC
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.verify_rider_pin(p_pin TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_rider RECORD;
BEGIN
  IF p_pin IS NULL OR LENGTH(TRIM(p_pin)) != 4 THEN
    RETURN jsonb_build_object('valid', false, 'error', 'Invalid PIN format');
  END IF;

  SELECT id, name, phone, vehicle, status, avatar, avatar_img, earnings, trips
  INTO v_rider
  FROM public.riders
  WHERE pin = TRIM(p_pin)
  LIMIT 1;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('valid', false, 'error', 'Incorrect rider passcode');
  END IF;

  RETURN jsonb_build_object(
    'valid', true,
    'rider', jsonb_build_object(
      'id', v_rider.id,
      'name', v_rider.name,
      'phone', v_rider.phone,
      'vehicle', v_rider.vehicle,
      'status', v_rider.status,
      'avatar', v_rider.avatar,
      'avatarImg', v_rider.avatar_img,
      'earnings', COALESCE(v_rider.earnings, 0),
      'trips', COALESCE(v_rider.trips, 0)
    )
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.verify_rider_pin(TEXT) TO anon, authenticated;
