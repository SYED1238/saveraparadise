-- ==============================================================================
-- SAVERA PARADISE - MIGRATION 04: CASHFREE SCHEMA & RLS ALIGNMENT
-- ==============================================================================
-- Resolves:
-- 1. Webhook update failures by adding is_paid_online & Cashfree tracking columns
-- 2. Category custom image persistence by adding categories.image column
-- 3. Guest checkout .select('tracking_token') RLS failure
-- 4. App-layer PIN-based Admin, Owner, and Rider mutation permissions
-- ==============================================================================

SET lock_timeout = '3s';

-- ------------------------------------------------------------------------------
-- 1. EXTEND ORDERS TABLE WITH CASHFREE & DOORSTEP UPI COLUMNS
-- ------------------------------------------------------------------------------
ALTER TABLE IF EXISTS public.orders 
  ADD COLUMN IF NOT EXISTS is_paid_online BOOLEAN DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS payment_gateway VARCHAR(32) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS cf_order_id VARCHAR(128) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS cf_payment_id VARCHAR(128) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS cf_payment_status VARCHAR(32) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS doorstep_upi BOOLEAN DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS doorstep_upi_vpa VARCHAR(128) DEFAULT NULL;

CREATE INDEX IF NOT EXISTS idx_orders_cf_order_id ON public.orders(cf_order_id);
CREATE INDEX IF NOT EXISTS idx_orders_tracking_token ON public.orders(tracking_token);

COMMENT ON COLUMN public.orders.is_paid_online IS 'True when payment is confirmed by Cashfree webhook or storefront PG';
COMMENT ON COLUMN public.orders.cf_order_id IS 'Unique order ID generated by or sent to Cashfree PG';
COMMENT ON COLUMN public.orders.cf_payment_id IS 'Cashfree transaction reference ID upon payment capture';
COMMENT ON COLUMN public.orders.doorstep_upi IS 'True when converted to dynamic PhonePe/UPI QR at delivery';

-- ------------------------------------------------------------------------------
-- 2. EXTEND CATEGORIES TABLE WITH IMAGE COLUMN
-- ------------------------------------------------------------------------------
ALTER TABLE IF EXISTS public.categories
  ADD COLUMN IF NOT EXISTS image TEXT;

COMMENT ON COLUMN public.categories.image IS 'Cloudflare R2 proxy URL or uploaded dish category icon';

-- ------------------------------------------------------------------------------
-- 3. EXTEND RIDERS TABLE WITH PAYOUT ATTRIBUTES
-- ------------------------------------------------------------------------------
ALTER TABLE IF EXISTS public.riders
  ADD COLUMN IF NOT EXISTS upi_vpa VARCHAR(64) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS bank_account_no VARCHAR(32) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS bank_ifsc VARCHAR(16) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS payout_method_pref VARCHAR(16) DEFAULT 'cash';

-- ------------------------------------------------------------------------------
-- 4. RLS POLICY ALIGNMENT FOR PIN-AUTHENTICATED PORTALS & GUEST CHECKOUT
-- ------------------------------------------------------------------------------
-- Because Kitchen Admin, Restaurant Owner, and Delivery Fleet authenticate via
-- app-layer passcodes and connect to Supabase via VITE_SUPABASE_ANON_KEY,
-- policies must allow anon-role operations while PostgreSQL immutability triggers
-- (prevent_status_regression, enforce_order_immutability) guarantee order integrity.

-- 4.1 Orders: Permit guest tracking_token retrieval & app-layer status updates
DROP POLICY IF EXISTS "orders_select_owner_or_staff" ON public.orders;
DROP POLICY IF EXISTS "orders_update_staff_only" ON public.orders;
DROP POLICY IF EXISTS "app_read_orders" ON public.orders;
DROP POLICY IF EXISTS "app_update_orders" ON public.orders;

CREATE POLICY "app_read_orders" ON public.orders 
  FOR SELECT USING (true);

CREATE POLICY "app_update_orders" ON public.orders 
  FOR UPDATE USING (true) WITH CHECK (true);

-- 4.2 Dishes & Categories: Allow admin dish updates & category photo saves
DROP POLICY IF EXISTS "admin_manage_dishes" ON public.dishes;
DROP POLICY IF EXISTS "app_manage_dishes" ON public.dishes;
CREATE POLICY "app_manage_dishes" ON public.dishes 
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "admin_manage_categories" ON public.categories;
DROP POLICY IF EXISTS "app_manage_categories" ON public.categories;
CREATE POLICY "app_manage_categories" ON public.categories 
  FOR ALL USING (true) WITH CHECK (true);

-- 4.3 Store Settings: Allow manager to toggle store open/close & MOV
DROP POLICY IF EXISTS "admin_manage_store_settings" ON public.store_settings;
DROP POLICY IF EXISTS "app_manage_store_settings" ON public.store_settings;
CREATE POLICY "app_manage_store_settings" ON public.store_settings 
  FOR ALL USING (true) WITH CHECK (true);

-- 4.4 Riders: Allow fleet roster management
DROP POLICY IF EXISTS "public_read_riders" ON public.riders;
DROP POLICY IF EXISTS "riders_staff_only" ON public.riders;
DROP POLICY IF EXISTS "app_manage_riders" ON public.riders;
CREATE POLICY "app_manage_riders" ON public.riders 
  FOR ALL USING (true) WITH CHECK (true);

-- ------------------------------------------------------------------------------
-- 5. SECURE RIDER PIN VERIFICATION RPC
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.verify_rider_pin(p_pin TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_rider RECORD;
BEGIN
  IF p_pin IS NULL OR LENGTH(TRIM(p_pin)) != 4 THEN
    RETURN jsonb_build_object('valid', false, 'error', 'Invalid PIN format');
  END IF;

  SELECT id, name, phone, vehicle, status, avatar, avatar_img, earnings, trips
  INTO v_rider
  FROM public.riders
  WHERE pin = TRIM(p_pin)
  LIMIT 1;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('valid', false, 'error', 'Incorrect rider passcode');
  END IF;

  RETURN jsonb_build_object(
    'valid', true,
    'rider', jsonb_build_object(
      'id', v_rider.id,
      'name', v_rider.name,
      'phone', v_rider.phone,
      'vehicle', v_rider.vehicle,
      'status', v_rider.status,
      'avatar', v_rider.avatar,
      'avatarImg', v_rider.avatar_img,
      'earnings', COALESCE(v_rider.earnings, 0),
      'trips', COALESCE(v_rider.trips, 0)
    )
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.verify_rider_pin(TEXT) TO anon, authenticated;
