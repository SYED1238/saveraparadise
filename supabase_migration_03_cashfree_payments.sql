-- ==============================================================================
-- MIGRATION 03: CASHFREE PAYMENTS & DOORSTEP DYNAMIC UPI INTEGRATION
-- ==============================================================================
-- Adds tracking columns for Cashfree Payment Gateway, Doorstep UPI payments,
-- and Rider Payout VPA/Bank details for end-of-day settlements.

-- 1. Extend orders table with Cashfree PG and Doorstep UPI attributes
ALTER TABLE IF EXISTS public.orders 
ADD COLUMN IF NOT EXISTS payment_gateway VARCHAR(32) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS cf_order_id VARCHAR(128) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS cf_payment_id VARCHAR(128) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS cf_payment_status VARCHAR(32) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS doorstep_upi BOOLEAN DEFAULT FALSE,
ADD COLUMN IF NOT EXISTS doorstep_upi_vpa VARCHAR(128) DEFAULT NULL;

-- Index for instant webhook lookups on Cashfree order ID
CREATE INDEX IF NOT EXISTS idx_orders_cf_order_id ON public.orders(cf_order_id);

-- 2. Extend riders table with UPI VPA and bank payout information
ALTER TABLE IF EXISTS public.riders
ADD COLUMN IF NOT EXISTS upi_vpa VARCHAR(64) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS bank_account_no VARCHAR(32) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS bank_ifsc VARCHAR(16) DEFAULT NULL,
ADD COLUMN IF NOT EXISTS payout_method_pref VARCHAR(16) DEFAULT 'cash';

-- Comments for database documentation
COMMENT ON COLUMN public.orders.cf_order_id IS 'Unique order ID generated by or sent to Cashfree PG';
COMMENT ON COLUMN public.orders.cf_payment_id IS 'Cashfree transaction reference number upon successful payment';
COMMENT ON COLUMN public.orders.doorstep_upi IS 'True when a COD order is converted to PhonePe/UPI at customer doorstep';
COMMENT ON COLUMN public.riders.upi_vpa IS 'Rider PhonePe/GooglePay UPI VPA for automated nighttime payouts';
